import { describe, expect, it, vi } from 'vitest';
import type { SupabaseClient } from '@supabase/supabase-js';
import { createStmProject, duplicateProject, ProjectCopyError } from '@/lib/projects/stm';

function mockSupabase(
  source: { data: unknown; error: unknown },
  created: { data: unknown; error: unknown } = { data: { id: 99 }, error: null },
  existing: { data: unknown; error: unknown } = { data: null, error: null }
) {
  const sourceSingle = vi.fn().mockResolvedValue(source);
  const existingMaybeSingle = vi.fn().mockResolvedValue(existing);
  // select('*').eq('id') loads the source; select('id').eq().eq() looks up an existing copy
  const eq = vi.fn().mockReturnValue({
    single: sourceSingle,
    eq: vi.fn().mockReturnValue({ maybeSingle: existingMaybeSingle }),
  });
  const select = vi.fn().mockReturnValue({ eq });

  const createdSingle = vi.fn().mockResolvedValue(created);
  const insertSelect = vi.fn().mockReturnValue({ single: createdSingle });
  const insert = vi.fn().mockReturnValue({ select: insertSelect });

  const from = vi.fn().mockReturnValue({ select, insert });
  return { supabase: { from } as unknown as SupabaseClient, eq, insert };
}

const source = {
  id: 7,
  created_at: '2026-01-01T00:00:00Z',
  updated_at: '2026-01-02T00:00:00Z',
  name: 'Alpha',
  system: 'A86',
  sap_subproject_id: '6690-58',
  sap_import_key: 'STD|A86|deDE|ptBR|LANGPAIR|DEADLINE|INITIAL',
  final_deadline: '2026-11-09T15:45:00Z',
  // Generated by the database: writing it would fail the insert
  closest_deadline: '2026-11-09T15:45:00Z',
};

const duplicateKey = { data: null, error: { code: '23505', message: 'duplicate key' } };

describe('createStmProject', () => {
  it('reads the source from the database and inserts an STM copy without identity or generated fields', async () => {
    const { supabase, eq, insert } = mockSupabase({ data: source, error: null });
    await expect(createStmProject(supabase, 7)).resolves.toEqual({ id: 99 });
    expect(eq).toHaveBeenCalledWith('id', 7);
    expect(insert).toHaveBeenCalledWith({
      name: 'Alpha',
      system: 'STM',
      sap_subproject_id: '6690-58',
      sap_import_key: 'STM|A86|deDE|ptBR|LANGPAIR|DEADLINE|INITIAL',
      final_deadline: '2026-11-09T15:45:00Z',
    });
  });

  it('keeps a null import key null', async () => {
    const { supabase, insert } = mockSupabase({ data: { ...source, sap_import_key: null }, error: null });
    await createStmProject(supabase, 7);
    expect(insert.mock.calls[0][0].sap_import_key).toBeNull();
  });

  it('explains that the project already has an STM copy, pointing at it', async () => {
    const { supabase } = mockSupabase({ data: source, error: null }, duplicateKey, {
      data: { id: 5069 },
      error: null,
    });
    const error = await createStmProject(supabase, 7).catch((e: unknown) => e);
    expect(error).toBeInstanceOf(ProjectCopyError);
    expect((error as ProjectCopyError).message).toBe(
      'This project already has an STM project. To make another copy, choose “Duplicate project”.'
    );
    expect((error as ProjectCopyError).existingProjectId).toBe(5069);
  });

  it('refuses to make an STM copy of an STM project', async () => {
    const { supabase, insert } = mockSupabase({ data: { ...source, system: 'STM' }, error: null });
    await expect(createStmProject(supabase, 7)).rejects.toThrow('This project is already an STM project');
    expect(insert).not.toHaveBeenCalled();
  });

  it('keeps the raw error for a duplicate on a project without an import key', async () => {
    const { supabase } = mockSupabase({ data: { ...source, sap_import_key: null }, error: null }, duplicateKey);
    await expect(createStmProject(supabase, 7)).rejects.toThrow('Failed to create STM project: duplicate key');
  });

  it('fails when the source cannot be loaded', async () => {
    const { supabase, insert } = mockSupabase({ data: null, error: { message: 'not found' } });
    await expect(createStmProject(supabase, 7)).rejects.toThrow('Failed to load source project: not found');
    expect(insert).not.toHaveBeenCalled();
  });

  it('fails when the insert fails', async () => {
    const { supabase } = mockSupabase({ data: source, error: null }, { data: null, error: { message: 'rls' } });
    await expect(createStmProject(supabase, 7)).rejects.toThrow('Failed to create STM project: rls');
  });
});

describe('duplicateProject', () => {
  it('copies every field, keeping the system, under a new import key', async () => {
    const { supabase, insert } = mockSupabase({ data: source, error: null });
    await expect(duplicateProject(supabase, 7)).resolves.toEqual({ id: 99 });

    const { sap_import_key, ...copied } = insert.mock.calls[0][0];
    expect(copied).toEqual({
      name: 'Alpha',
      system: 'A86',
      sap_subproject_id: '6690-58',
      final_deadline: '2026-11-09T15:45:00Z',
    });
    expect(sap_import_key).toMatch(/^DUP\|[0-9a-f-]{36}$/);
  });

  it("applies the PM's changes over the copied fields, but never their import key", async () => {
    const { supabase, insert } = mockSupabase({ data: source, error: null });
    await duplicateProject(supabase, 7, { system: 'B0X', work_list: ['0010'], sap_import_key: 'STD|x' });

    const inserted = insert.mock.calls[0][0];
    expect(inserted).toMatchObject({ name: 'Alpha', system: 'B0X', work_list: ['0010'] });
    expect(inserted.sap_import_key).toMatch(/^DUP\|/);
  });

  it('gives every duplicate a different import key', async () => {
    const { supabase, insert } = mockSupabase({ data: source, error: null });
    await duplicateProject(supabase, 7);
    await duplicateProject(supabase, 7);
    expect(insert.mock.calls[0][0].sap_import_key).not.toBe(insert.mock.calls[1][0].sap_import_key);
  });

  it('fails when the insert fails', async () => {
    const { supabase } = mockSupabase({ data: source, error: null }, { data: null, error: { message: 'rls' } });
    await expect(duplicateProject(supabase, 7)).rejects.toThrow('Failed to duplicate project: rls');
  });
});
